let a = 5;
console.log("Value of a: " , a);
a += 5; // a = a + 5
console.log("Value of a after += 5: " , a);

a -= 3; // a = a - 3
console.log("Value of a after -= 3: " , a);

a*= 2; // a = a * 2
console.log("Value of a after *= 2: " , a);

a /= 4; // a = a / 4
console.log("Value of a after /= 4: " , a);

a%= 2; // a = a % 2
console.log("Value of a after %= 2: " , a);

a **= 3; // a = a ** 3
console.log("Value of a after **= 3: " , a);

